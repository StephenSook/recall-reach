// The last step after APIMatic generates the SDK and the docs portal. Its templates write dashes and curly quotes, which
// our own writing doesn't use. In prose a dash between words becomes a comma. In a script or a style sheet a character
// left over becomes its escape, which is the same character to the code, so nothing it does can change.
//   pnpm exec tsx scripts/apimatic-tidy.ts sdk/typescript public/api-docs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";

const BANNED = /[\u2013\u2014\u2018\u2019\u201c\u201d]/g;
/** A dash between words, with its spaces: "referenced, run". In a page and in the script that draws it alike. */
const BETWEEN_WORDS = / +\u2014 +/g;
/** A dash alone in a Markdown table cell is a minus, not a pause. */
const TABLE_CELL = /\| *\u2014 *(?=\|)/g;
/** A character standing alone in a script, as in a table of HTML entities: code, so it keeps its value. */
const ALONE_IN_SCRIPT = /`([\u2013\u2014\u2018\u2019\u201c\u201d])`/g;
const DASHES = /[\u2013\u2014]/g;
const PLAIN: Record<string, string> = { "\u2013": "-", "\u2014": "-", "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"' };
const TEXT = new Set([".md", ".mdx", ".txt", ".html", ".xml", ".ts", ".json", ".js", ".mjs", ".css", ".map"]);

const hex = (ch: string) => ch.charCodeAt(0).toString(16).toUpperCase().padStart(4, "0");

export function tidy(text: string, ext: string): string {
  const prose = text.replace(TABLE_CELL, "| - ").replace(BETWEEN_WORDS, ", ");
  if (ext === ".js" || ext === ".mjs" || ext === ".map") {
    // A dash left over reads as a minus in the page as well as here. A curly quote keeps its value, as its escape, since a
    // straight one could close the string it sits in.
    return prose
      .replace(ALONE_IN_SCRIPT, (_all, ch: string) => `\`\\u${hex(ch)}\``)
      .replace(DASHES, "-")
      .replace(BANNED, (ch) => `\\u${hex(ch)}`);
  }
  if (ext === ".css") return prose.replace(BANNED, (ch) => `\\${hex(ch)}`);
  // In JSON a straight double quote would end the string it's in.
  if (ext === ".json") return prose.replace(BANNED, (ch) => (ch === "\u201c" || ch === "\u201d" ? '\\"' : PLAIN[ch]));
  return prose.replace(BANNED, (ch) => PLAIN[ch]);
}

/** Kept in the SDK's README across regenerations: the licence there is APIMatic's template, so this says what the code is. */
export const PROVENANCE = "Generated by APIMatic's CLI from this repository's [openapi.yaml](../../openapi.yaml).";

export function withProvenance(readme: string): string {
  if (readme.includes(PROVENANCE)) return readme;
  const title = readme.indexOf("\n");
  return title === -1 ? `${readme}\n\n${PROVENANCE}\n` : `${readme.slice(0, title)}\n\n${PROVENANCE}${readme.slice(title)}`;
}

function walk(dir: string, changed: string[]): void {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name === "dist" || name === ".tshy") continue;
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path, changed);
    else if (TEXT.has(extname(name))) {
      const before = readFileSync(path, "utf8");
      const tidied = tidy(before, extname(name));
      const after = name === "README.md" && dir.endsWith("sdk/typescript") ? withProvenance(tidied) : tidied;
      if (after !== before) {
        writeFileSync(path, after);
        changed.push(path);
      }
    }
  }
}

if (process.argv[1]?.endsWith("apimatic-tidy.ts")) {
  const changed: string[] = [];
  for (const dir of process.argv.slice(2)) walk(dir, changed);
  console.log(`tidied ${changed.length} files`);
}
