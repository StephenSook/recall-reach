"use client";

import { useRef, useState } from "react";
import type { DoorNotice as Notice } from "@/server/notice/door";
import { CpscInSpanish } from "@/app/r/CpscInSpanish";

export function DoorNotice({ notice, noticeId, publicUrl, qr }: { notice: Notice; noticeId: string; publicUrl: string; qr: string }) {
  const [showDates, setShowDates] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const actionId = useRef<string | null>(null);

  async function print() {
    if (busy) return;
    setBusy(true);
    setError(null);
    actionId.current ??= crypto.randomUUID();
    try {
      const res = await fetch(`/api/queue/notices/${noticeId}/door`, {
        method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ actionId: actionId.current }),
      });
      if (!res.ok) throw new Error("The print action could not be recorded. Try again.");
      actionId.current = null;
      window.print();
    } catch {
      setError("The print action could not be recorded. Try again.");
    } finally {
      setBusy(false);
    }
  }

  return (
    <main className="door-page">
      <div className="door-controls">
        {notice.firstSale && notice.lastSale ? (
          <label><input type="checkbox" checked={showDates} onChange={(e) => setShowDates(e.target.checked)} /> Show sale dates</label>
        ) : null}
        <div className="actions">
          <button type="button" className="btn" disabled={busy} onClick={() => void print()}>Print door notice</button>
          <a href="/queue">Back to the queue</a>
        </div>
        <p className="note">Records this print action. Your browser cannot confirm that paper was printed.</p>
        {error ? <p role="alert">{error}</p> : null}
      </div>
      <article className="door-notice">
        {notice.demo ? <p>Demo shop</p> : null}
        <h1>{notice.title}</h1>
        <p>CPSC recall {notice.recallNumber}. Recall date: {notice.recallDate}.</p>
        {showDates && notice.firstSale && notice.lastSale ? <p>We sold this item between {notice.firstSale} and {notice.lastSale}</p> : null}
        <h2>The hazard, in CPSC&apos;s words</h2>
        {notice.hazards.map((text, i) => <p key={i} className="door-words">{text}</p>)}
        <h2>What to do, in CPSC&apos;s words</h2>
        {notice.remedies.map((text, i) => <p key={i} className="door-words">{text}</p>)}
        <h2>Contact from CPSC&apos;s record</h2>
        <p className="door-words">{notice.consumerContact ?? "Contact details are not held in this record. Read CPSC's recall page."}</p>
        <CpscInSpanish />
        <h2>Read the recall on your phone</h2>
        <div className="door-recall-link">
          {/* Local SVG data, generated by qrcode. No remote image request. */}
          {/* eslint-disable-next-line @next/next/no-img-element */}
          <img className="door-qr" src={qr} width={240} height={240} alt="Scan to read the recall" />
          <a className="door-url" href={publicUrl}>{publicUrl}</a>
        </div>
        <p><a href={notice.recallUrl}>CPSC&apos;s recall page: {notice.recallUrl}</a></p>
      </article>
    </main>
  );
}
