"use client";

/** The whole address is long and means nothing to read: the code and the link carry it. */
export const shortReceiptLink = (link: string): string => `${new URL(link).host}/s/...`;

export function ReceiptCard({ link, qr, demo, kept, deletesAfter }: { link: string; qr: string; demo: boolean; kept: boolean; deletesAfter: string }) {
  return (
    <section className="window safety-receipt-card">
      <header className="window-bar"><h2>Safety receipt</h2>{demo ? <span className="chip">DEMO SHOP</span> : null}</header>
      <div className="window-body">
        <p>Let a family ask for recall updates at checkout.</p>
        {kept ? (
          <p>Receipts saved here are kept for up to 3 years, or until this shop&apos;s data is deleted. Your shop is kept while you sign in with PayPal at least once a year: it&apos;s due to be deleted after {deletesAfter}.</p>
        ) : (
          <p>Receipts saved here are deleted with this shop&apos;s data after {deletesAfter}.</p>
        )}
        {/* Local SVG data, generated by qrcode. No remote image request. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={qr} width={240} height={240} alt="Scan to save a safety receipt" />
        <p><a href={link} className="receipt-link"><span className="receipt-short">{shortReceiptLink(link)}</span><span className="receipt-full">{link}</span></a></p>
        <div className="actions receipt-no-print">
          <button className="btn btn-outline" type="button" onClick={() => window.print()}>Print QR and link</button>
          <a className="btn btn-outline" href="/queue/safety-receipts">Manage receipts</a>
        </div>
      </div>
      <style>{`
        .receipt-link { overflow-wrap: anywhere; }
        .receipt-full { display: none; }
        @media print {
          .receipt-short { display: none; }
          .receipt-full { display: inline; }
          body > :not(main), main > :not(.safety-receipt-card) { display: none !important; }
          .safety-receipt-card { position: static; width: 100%; break-inside: avoid; }
          .safety-receipt-card .receipt-no-print { display: none; }
        }
      `}</style>
    </section>
  );
}
